import { z } from 'zod';

/** Shared contract schemas (named components in the OpenAPI documents). Money is ALWAYS integer piastres. */

export const piastres = z.number().int().meta({ description: 'Amount in piastres (1 EGP = 100 piastres). Format with the shared money formatter, never as a float.' });
export const isoDateTime = z.string().meta({ format: 'date-time' });
export const uuid = z.uuid();
export const slug = z.string().trim().min(1).max(200);

export const deviceInfo = z
  .object({
    installationId: z.string().regex(/^[A-Za-z0-9_-]{16,128}$/).meta({ description: 'Random per-installation id generated by the app and kept in secure storage.' }),
    platform: z.enum(['IOS', 'ANDROID']),
    deviceName: z.string().max(80).optional(),
    appVersion: z.string().regex(/^[0-9A-Za-z.+_-]{1,32}$/).optional(),
  })
  .meta({ id: 'DeviceInfo' });

export const tokenPair = z
  .object({
    accessToken: z.string(),
    accessTokenExpiresAt: isoDateTime,
    refreshToken: z.string().meta({ description: 'Single use. Store only in Keychain/Keystore. A reused refresh token revokes the session.' }),
    sessionExpiresAt: isoDateTime,
  })
  .meta({ id: 'TokenPair' });

export const sessionResult = z
  .object({
    user: z.object({ id: uuid, fullName: z.string(), isStaff: z.boolean() }),
    tokens: tokenPair,
    deviceId: uuid,
    mfa: z.object({ required: z.boolean(), enrolled: z.boolean() }),
  })
  .meta({ id: 'SessionResult' });

export const profile = z
  .object({
    id: uuid,
    fullName: z.string(),
    email: z.string().nullable(),
    phone: z.string().nullable(),
    locale: z.enum(['ar', 'en']),
    emailVerified: z.boolean(),
    phoneVerified: z.boolean(),
    isStaff: z.boolean(),
    totpEnrolled: z.boolean(),
    permissions: z.array(z.string()),
  })
  .meta({ id: 'Profile' });

export const deviceSession = z
  .object({
    id: z.string().meta({ description: 'Opaque session handle (not the session secret).' }),
    scope: z.enum(['WEB', 'ADMIN', 'MOBILE', 'ADMIN_MOBILE']),
    current: z.boolean(),
    createdAt: isoDateTime,
    lastSeenAt: isoDateTime,
    expiresAt: isoDateTime,
    device: z.object({ platform: z.string(), name: z.string().nullable(), appVersion: z.string().nullable(), app: z.string() }).nullable(),
    userAgent: z.string().nullable(),
  })
  .meta({ id: 'DeviceSession' });

export const sessionList = z.object({ items: z.array(deviceSession) });
export const revokedCount = z.object({ revoked: z.number().int() });
export const ok = z.object({ ok: z.literal(true) }).meta({ id: 'Ok' });

export const category: z.ZodType<{ id: string; slug: string; nameAr: string; nameEn: string; icon: string | null; children: unknown[] }> = z
  .object({
    id: uuid,
    slug: z.string(),
    nameAr: z.string(),
    nameEn: z.string(),
    icon: z.string().nullable(),
    get children() {
      return z.array(category);
    },
  })
  .meta({ id: 'Category' });

export const storeRef = z.object({ name: z.string(), slug: z.string(), verified: z.boolean() });

export const productCard = z
  .object({
    id: uuid,
    slug: z.string(),
    titleAr: z.string(),
    condition: z.enum(['NEW', 'USED']),
    usedGrade: z.string().nullable(),
    minPricePiastres: piastres.nullable(),
    compareAtPricePiastres: piastres.nullable(),
    inStock: z.boolean(),
    ratingAvg: z.number(),
    ratingCount: z.number().int(),
    store: storeRef,
    imageUrl: z.string().nullable(),
    defaultVariantId: uuid.nullable(),
    variantCount: z.number().int(),
  })
  .meta({ id: 'ProductCard' });

export const page = <T extends z.ZodType>(item: T) => z.object({ items: z.array(item), page: z.number().int(), pageSize: z.number().int(), total: z.number().int(), pages: z.number().int() });

const spec = z.object({ code: z.string(), name: z.string(), value: z.string() });

export const productDetail = z
  .object({
    id: uuid,
    slug: z.string(),
    titleAr: z.string(),
    titleEn: z.string().nullable(),
    description: z.string().nullable(),
    keyFeatures: z.array(z.string()),
    condition: z.enum(['NEW', 'USED']),
    usedGrade: z.string().nullable(),
    conditionNotes: z.string().nullable(),
    defects: z.string().nullable(),
    includedAccessories: z.string().nullable(),
    warrantyInfo: z.string().nullable(),
    processingDays: z.number().int().nullable(),
    ratingAvg: z.number(),
    ratingCount: z.number().int(),
    brand: z.object({ id: uuid, slug: z.string(), name: z.string(), nameAr: z.string().nullable() }).nullable(),
    category: z.object({ id: uuid, slug: z.string(), nameAr: z.string(), nameEn: z.string() }).nullable(),
    breadcrumbs: z.array(z.object({ id: uuid, slug: z.string(), nameAr: z.string(), nameEn: z.string() })),
    store: storeRef.extend({ ratingAvg: z.number(), ratingCount: z.number().int() }),
    images: z.array(z.object({ url: z.string(), thumbUrl: z.string(), alt: z.string().nullable(), isActualItem: z.boolean(), width: z.number().int().nullable(), height: z.number().int().nullable() })),
    specs: z.array(spec),
    variants: z.array(
      z.object({
        id: uuid,
        label: z.string(),
        options: z.record(z.string(), z.string()),
        pricePiastres: piastres,
        compareAtPricePiastres: piastres.nullable(),
        available: z.boolean().meta({ description: 'Availability only; stock counts are never exposed.' }),
        specs: z.array(spec),
      }),
    ),
  })
  .meta({ id: 'ProductDetail' });

export const review = z
  .object({ id: uuid, rating: z.number().int(), title: z.string().nullable(), body: z.string().nullable(), author: z.string(), sellerResponse: z.string().nullable(), createdAt: isoDateTime })
  .meta({ id: 'Review' });

export const storeView = z
  .object({
    name: z.string(),
    slug: z.string(),
    description: z.string().nullable(),
    verified: z.boolean(),
    logoUrl: z.string().nullable(),
    bannerUrl: z.string().nullable(),
    ratingAvg: z.number(),
    ratingCount: z.number().int(),
    positivePercent: z.number().int().nullable(),
    memberSince: isoDateTime.nullable(),
    acceptsVoluntaryReturns: z.boolean(),
    voluntaryReturnDays: z.number().int().nullable(),
    productCount: z.number().int(),
    categories: z.array(z.object({ nameAr: z.string(), slug: z.string() })),
    reviews: z.array(review),
  })
  .meta({ id: 'Store' });
